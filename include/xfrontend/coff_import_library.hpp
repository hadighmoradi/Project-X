#pragma once

#include "xfrontend/archive.hpp"

#include <cstddef>
#include <cstdint>
#include <string>
#include <vector>

namespace xfrontend {

constexpr std::uint16_t CoffMachineAmd64 = 0x8664U;

enum class CoffImportType : std::uint16_t {
    Code = 0U,
    Data = 1U,
    Const = 2U
};

enum class CoffImportNameType : std::uint16_t {
    Ordinal = 0U,
    Name = 1U,
    NameNoPrefix = 2U,
    NameUndecorate = 3U
};

// Description of one AMD64 short-import member. For NameType::Ordinal,
// ordinal_or_hint is the non-zero export ordinal. Otherwise it is the hint.
// A zero timestamp is deterministic and is the default.
struct CoffImportSymbol {
    std::string dll_name;
    std::string symbol_name;
    CoffImportType type = CoffImportType::Code;
    CoffImportNameType name_type = CoffImportNameType::Name;
    std::uint16_t ordinal_or_hint = 0U;
    std::uint32_t timestamp = 0U;
    // Empty uses the DLL basename. Every object for one DLL must share the
    // same archive-member name so MSVC can resolve .idata section-class symbols.
    std::string member_name;
};

struct CoffShortImportObject {
    std::uint16_t machine = CoffMachineAmd64;
    std::uint32_t timestamp = 0U;
    std::string symbol_name;
    std::string dll_name;
    CoffImportType type = CoffImportType::Code;
    CoffImportNameType name_type = CoffImportNameType::Name;
    std::uint16_t ordinal_or_hint = 0U;
    std::string member_name;
};

struct CoffShortImportReadResult {
    CoffShortImportObject import_object;
    std::vector<Diagnostic> diagnostics;
    bool succeeded() const noexcept { return diagnostics.empty(); }
};

struct CoffImportLibraryWriteResult {
    std::vector<std::uint8_t> bytes;
    std::vector<Diagnostic> diagnostics;
    std::size_t import_count = 0U;
    bool succeeded() const noexcept { return diagnostics.empty() && bytes.size() >= 8U; }
};

struct CoffImportLibraryReadResult {
    ArchiveContainer archive;
    std::vector<CoffShortImportObject> imports;
    std::vector<Diagnostic> diagnostics;
    bool succeeded() const noexcept { return diagnostics.empty() && archive.format == ArchiveFormat::CoffLib; }
};

// Short-import objects are the canonical compact members of a Windows COFF
// import library. The resulting .lib uses the N31 COFF archive writer and its
// dual linker-member symbol index. The current target is AMD64 only.
CoffImportLibraryWriteResult write_coff_import_library(
    const std::vector<CoffImportSymbol>& imports,
    std::uint16_t machine = CoffMachineAmd64);

CoffShortImportReadResult read_coff_short_import_object(
    const std::vector<std::uint8_t>& bytes);

// Reads only compact short-import members generated by this API. Traditional
// long-form import objects, ARM64/ARM64EC, and NAME_EXPORTAS are not implied.
CoffImportLibraryReadResult read_coff_import_library(
    const std::vector<std::uint8_t>& bytes);

// Returns the COFF linker symbols supplied by one short-import object:
// CODE supplies the callable thunk and __imp_ data symbol; DATA supplies only
// __imp_; CONST supplies both the public data name and __imp_ data symbol.
std::vector<std::string> coff_import_linker_symbols(
    const CoffShortImportObject& import_object);

} // namespace xfrontend
